// Runs after `vite build` (npm "postbuild"). Firebase Hosting rewrites every
// URL without its own prerendered file to dist/client/_shell.html — and that
// shell is rendered at "/", so it carries the homepage's rel=canonical and
// og:url. Served as-is for /product/<id> (and any other dynamic route), the
// raw HTML told search engines every product page was a duplicate of the
// homepage. This keeps the homepage's head on its own index.html and strips
// the homepage-only tags from the shell; each route sets its own once it
// renders.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dist = fileURLToPath(new URL("../dist/client/", import.meta.url));
const shellPath = `${dist}_shell.html`;

// The shell has no page in it, only the slot one goes in. The app hydrates
// that slot as it is and fills it afterwards (see ShellOutlet); this flag is
// how it knows the HTML it's hydrating is the shell and not a prerendered
// page. The home page's index.html is the shell too, so it gets it as well.
const SHELL_FLAG_SCRIPT = "<script>window.__EP_SHELL__=true</script>";
const HEAD_TAG = /<head(\s[^>]*)?>/;
let shell = readFileSync(shellPath, "utf8");
if (!HEAD_TAG.test(shell)) throw new Error("finalize-hosting: no <head> in _shell.html");
shell = shell.replace(HEAD_TAG, (tag) => `${tag}${SHELL_FLAG_SCRIPT}`);
writeFileSync(`${dist}index.html`, shell);

const HOME_ONLY_TAGS = [
  /<link rel="canonical" href="[^"]*"\s*\/?>/g,
  /<meta property="og:url" content="[^"]*"\s*\/?>/g,
];

for (const tag of HOME_ONLY_TAGS) {
  // Fail loudly if the markup ever changes shape — silently skipping this
  // would bring the duplicate-canonical problem straight back.
  if (!shell.match(tag)) throw new Error(`finalize-hosting: ${tag} not found in _shell.html`);
  shell = shell.replace(tag, "");
}
writeFileSync(shellPath, shell);
console.log(
  "finalize-hosting: index.html written, shell flagged, homepage canonical/og:url removed from the shell",
);

// /sitemap.xml is generated by the API through a Hosting rewrite (it lists
// every product). Hosting serves a static file first, so one in the build
// would silently replace it with a stale, hand-written list.
if (existsSync(`${dist}sitemap.xml`)) {
  throw new Error("finalize-hosting: dist/client/sitemap.xml would shadow the API's sitemap");
}
